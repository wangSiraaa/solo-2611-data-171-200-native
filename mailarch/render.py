def render_site(out: Path, top_nodes, attached_nodes, threads, report,
                mime_issue_count) -> None:
    nodes = {}
    for n in top_nodes + attached_nodes:
        nodes[n["node_id"]] = n
    ghosts = {g["node_id"]: g for g in threads["placeholders"]}
    ctx = _Ctx(nodes, ghosts, threads)

    for n in top_nodes + attached_nodes:
        body = _message_page(n, ctx)
        title = n.get("subject") or n["node_id"]
        (out / "messages" / f"{n['node_id']}.html").write_text(
            _page(title, body, "../"), encoding="utf-8")

    for c in threads["conversations"]:
        body = _thread_page(c, ctx)
        (out / "threads" / f"{c['conv_id']}.html").write_text(
            _page(c["subject"], body, "../"), encoding="utf-8")

    (out / "index.html").write_text(
        _page("mailarch 索引", _index(threads, ctx, report, mime_issue_count), ""),
        encoding="utf-8")

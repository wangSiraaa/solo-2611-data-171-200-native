# message pages
# ----------------------------------------------------------------------
def _message_page(node, ctx: _Ctx) -> str:
    nid = node["node_id"]
    tree = node["_tree"]
    parts = {p["path"]: p for p in node["parts"]}
    notes: list[tuple[str, str]] = []

    def note(kind, detail):
        notes.append((kind, detail))

    def resolver_for(part_path):
        scope = node["part_scope"].get(part_path)
        cmap = node["scopes"].get(scope, {}) if scope else {}

        def resolve(cid):
            target = cmap.get(cid)
            if not target:
                return None
            p = parts.get(target)
            if not p or not p.get("asset"):
                return None
            return ("../" + p["asset"], p["declared_type"])
        return resolve

    def render_text(path):
        p = parts[path]
        text = tree.text.get(path)
        if text is None:
            return '<p class="placeholder">(该 part 内容不可用)</p>'
        if p["declared_type"] == "text/html":
            return sanitize_html(text, resolver_for(path), note)
        return f'<pre class="body">{escape(text)}</pre>'

    out = [f"<h1>{escape(node.get('subject') or '(no subject)')}{_badges(node)}</h1>"]

    # -- metadata -------------------------------------------------------
    mid = escape(node["message_id"])
    if node["message_id_synthesized"]:
        mid += ' <span class="badge warn">synthesized</span>'
    rows = [
        ("节点", f'<span class="digest">{nid}</span>'),
        ("Message-ID", mid),
        ("From", escape(node.get("from") or "")),
        ("To", escape(node.get("to") or "")),
        ("Date", escape(node.get("date_raw") or "")),
        ("原始字节 SHA-256", f'<span class="digest">{node["raw_sha256"]}</span>'),
    ]
    if node["kind"] == "top":
        rows.append(("来源文件", escape(", ".join(node["source_files"]))))
    if node.get("digest_note"):
        rows.append(("摘要口径", escape(node["digest_note"])))
    out.append('<section><table class="meta">'
               + "".join(f"<tr><td>{k}</td><td>{v}</td></tr>" for k, v in rows)
               + "</table></section>")

    # -- threading / provenance navigation -------------------------------
    nav = []
    if node["kind"] == "top":
        conv = node.get("conversation")
        if conv and conv in ctx.conv:
            c = ctx.conv[conv]
            nav.append(f'会话: <a href="../threads/{conv}.html">{escape(c["subject"])}</a>'
                       f'({c["message_count"]} 封)')
        parent = node.get("parent")
        if parent == nid and parent:
            nav.append('父邮件: <span class="cycle">自引用(指向自身)</span>')
        elif parent:
            if parent in ctx.ghosts:
                nav.append(f'父邮件: <span class="placeholder">⚠ 缺失 '
                           f'{escape(ctx.ghosts[parent]["message_id"])}(占位节点)</span>')
            else:
                nav.append(f'父邮件: <a href="{parent}.html">'
                           f'{escape(ctx.node_label(parent))}</a>')
        for ap in node.get("ambiguous_parents", []):
            nav.append(f'候选父邮件(身份冲突未裁决): <a href="{ap}.html">'
                       f'{escape(ctx.node_label(ap))}</a>')
        kids = [k for k in node.get("children", []) if k in ctx.nodes]
        if kids:
            links = ", ".join(f'<a href="{k}.html">{escape(ctx.node_label(k))}</a>'
                              for k in kids)
            nav.append(f"回复: {links}")
    else:
        at = node.get("attached_to") or {}
        nav.append(f'本邮件为 message/rfc822 附件邮件，所属: '
                   f'<a href="{at.get("message", "")}.html">{at.get("message", "")}</a>'
                   f'(part {at.get("part", "")})')
        nav.append('<span class="placeholder">附件邮件不作为顶层会话成员</span>')
    if nav:
        out.append("<section><h2>关系</h2><ul>" +
                   "".join(f"<li>{x}</li>" for x in nav) + "</ul></section>")

    # -- reference evidence ----------------------------------------------
    ev = []
    if node.get("references"):
        ev.append("<li>References(完整有序证据链):<ul class=\"evidence\">"
                  + "".join(f"<li>{escape(r)}</li>" for r in node["references"]) + "</ul></li>")
    if node.get("in_reply_to"):
        ev.append("<li>In-Reply-To: " +
                  ", ".join(escape(x) for x in node["in_reply_to"]) + "</li>")
    if ev:
        out.append("<section><h2>引用证据</h2><ul>" + "".join(ev) + "</ul></section>")

    # -- body --------------------------------------------------------------
    body = node.get("body")
    out.append("<section><h2>正文</h2>")
    if body:
        fmt = body["format"]
        out.append(f'<div class="bodyfmt placeholder">primary body: part '
                   f'{escape(body["path"])} ({fmt})</div>')
        out.append(render_text(body["path"]))
    else:
        out.append('<p class="placeholder">(无可展示正文 part)</p>')
    out.append("</section>")

    for path in node.get("alternatives", []):
        p = parts[path]
        out.append(f'<details><summary>替代正文 {escape(p["declared_type"])} '
                   f'(part {escape(path)})</summary>{render_text(path)}</details>')

    inline_html = [p for p in node["parts"]
                   if p["role"] == "inline" and p["declared_type"] == "text/html"]
    for p in inline_html:
        out.append(f'<details><summary>内嵌 HTML 资源 (part {escape(p["path"])})</summary>'
                   f'{render_text(p["path"])}</details>')

    # -- attachments --------------------------------------------------------
    att = [p for p in node["parts"] if p["role"] == "attachment"]
    if att:
        rows = []
        for p in att:
            name = escape(p.get("display_name") or "(未命名)")
            link = (f'<a href="../{p["asset"]}" download>{name}</a>'
                    if p.get("asset") else name)
            rows.append(f"<tr><td>{link}</td><td>{escape(p['declared_type'])}</td>"
                        f"<td>{_size(p['size'])}</td>"
                        f'<td class="digest">{_short(p["sha256"])}</td>'
                        f"<td>{escape(p['path'])}</td></tr>")
        out.append("<section><h2>附件</h2><table><tr><th>名称(仅展示)</th><th>声明类型</th>"
                   "<th>大小</th><th>SHA-256</th><th>part</th></tr>"
                   + "".join(rows) + "</table></section>")

    # -- inline resources -----------------------------------------------------
    inl = [p for p in node["parts"] if p["role"] == "inline"]
    if inl:
        ref_by = {}
        for ref in node["cid_refs"]:
            if ref["bound_to"]:
                ref_by.setdefault(ref["bound_to"], []).append(ref["part"])
        rows = []
        for p in inl:
            link = (f'<a href="../{p["asset"]}" download>资源</a>'
                    if p.get("asset") else "(未导出)")
            refs = ", ".join(ref_by.get(p["path"], [])) or "—"
            rows.append(f"<tr><td>{escape(p.get('content_id') or '')}</td>"
                        f"<td>{escape(p['declared_type'])}</td><td>{link}</td>"
                        f"<td>{escape(refs)}</td>"
                        f'<td class="digest">{_short(p["sha256"])}</td>'
                        f"<td>{escape(p['path'])}</td></tr>")
        out.append("<section><h2>内嵌资源</h2><table><tr><th>Content-ID</th>"
                   "<th>声明类型</th><th>资源</th><th>被引用自 part</th><th>SHA-256</th>"
                   "<th>part</th></tr>" + "".join(rows) + "</table></section>")

    # -- attached messages ------------------------------------------------------
    if node.get("attached"):
        items = []
        for a in node["attached"]:
            child = ctx.nodes.get(a["node"], {})
            label = child.get("subject") or a["node"]
            items.append(f'<li><a href="{a["node"]}.html">{escape(label)}</a> '
                         f'<span class="digest">{a["node"]}</span> '
                         f'(part {escape(a["part"])})</li>')
        out.append("<section><h2>附带邮件 (message/rfc822)</h2><ul>"
                   + "".join(items) + "</ul></section>")

    # -- render notes ------------------------------------------------------------
    if notes:
        counts = Counter(notes)
        items = "".join(f"<li>{escape(k)}: {escape(str(d))} ×{n}</li>"
                        for (k, d), n in sorted(counts.items()))
        out.append(f"<section><h2>渲染说明</h2><ul>{items}</ul></section>")

    # -- full part table ------------------------------------------------------------
    rows = []
    for p in node["parts"]:
        rows.append(
            f"<tr><td>{escape(p['path'])}</td><td>{escape(p['declared_type'])}</td>"
            f"<td>{escape(p['cte'])}</td><td>{escape(p['role'])}</td>"
            f"<td>{_size(p['size'])}</td>"
            f'<td class="digest">{_short(p["sha256"])}</td>'
            f"<td>{escape(p.get('content_id') or '')}</td>"
            f"<td>{escape(p.get('display_name') or '')}</td></tr>")
    out.append("<section><h2>MIME 结构</h2><table><tr><th>part</th><th>声明类型</th>"
               "<th>CTE</th><th>实际角色</th><th>大小</th><th>SHA-256</th>"
               "<th>Content-ID</th><th>文件名(展示)</th></tr>"
               + "".join(rows) + "</table></section>")

    # -- issues ----------------------------------------------------------------------
    issues = list(node.get("issues", []))
    diags = ctx.diags_for(nid)
    if issues or diags:
        items = [f"<li>[MIME] part {escape(i['part'] or '-')}: {escape(i['code'])} — "
                 f"{escape(i['detail'])}</li>" for i in issues]
        items += [f"<li>[会话] {escape(d['type'])}: "
                  f"{escape(json.dumps(d, ensure_ascii=False, sort_keys=True))}</li>"
                  for d in diags]
        out.append("<section><h2>问题与诊断</h2><ul>" + "".join(items) + "</ul></section>")

    return "".join(out)



def _index(threads, ctx: _Ctx, report, mime_issue_count) -> str:
    def conv_key(c):
        dates = [ctx.nodes[m]["date_iso"] for m in c["members"]
                 if m in ctx.nodes and ctx.nodes[m].get("date_iso")]
        return (min(dates) if dates else "9999", c["conv_id"])

    rows = []
    for c in sorted(threads["conversations"], key=conv_key):
        flags = " ".join(f'<span class="badge warn">{escape(f)}</span>' for f in c["flags"])
        entry = ctx.any_node(c["entry"]) or {}
        rows.append(f'<tr><td><a href="threads/{c["conv_id"]}.html">'
                    f'{escape(c["subject"])}</a></td>'
                    f"<td>{c['message_count']}</td>"
                    f"<td>{escape(entry.get('date_iso') or '')}</td>"
                    f"<td>{flags}</td></tr>")
    out = ["<h1>邮件档案索引</h1>",
           f"<p>{len(threads['conversations'])} 个会话 · "
           f"{len(ctx.nodes)} 封邮件(含附件邮件) · "
           f"{len(threads['diagnostics'])} 条会话诊断 · "
           f"{mime_issue_count} 条 MIME 解析问题</p>",
           "<section><h2>会话</h2><table><tr><th>主题</th><th>邮件数</th>"
           "<th>起始日期</th><th>标记</th></tr>" + "".join(rows) + "</table></section>"]

    if threads["diagnostics"]:
        items = "".join(
            f"<li>{escape(d['type'])}: "
            f"{escape(json.dumps(d, ensure_ascii=False, sort_keys=True))}</li>"
            for d in threads["diagnostics"])
        out.append(f"<section><h2>会话诊断(全部)</h2><ul>{items}</ul></section>")

    sup = "".join(f"<li>{escape(s)}</li>" for s in report["supported"])
    uns = "".join(f"<li>{escape(s)}</li>" for s in report["unsupported"])
    out.append(f"<section><h2>支持范围</h2><ul>{sup}</ul>"
               f"<h2>不支持/不处理</h2><ul>{uns}</ul></section>")
    return "".join(out)



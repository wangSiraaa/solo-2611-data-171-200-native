"""Static read-only HTML rendering: index, conversation and message pages.

Pages contain no JavaScript and load no remote resources.  Bodies are
rendered only through the sanitizer; attachments and inline resources
are linked (never embedded active content).  From each message page the
reader can navigate to the conversation, parent/children, attached
messages, and from the body back to bound inline images and
attachments.
"""

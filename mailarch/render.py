def _thread_page(conv, ctx: _Ctx) -> str:
    children_map = ctx.threads["children_map"]

    def link(nid):
        n = ctx.any_node(nid)
        label = escape(ctx.node_label(nid))
        if n is None or n.get("placeholder"):
            return f'<span class="placeholder">{label}</span>'
        return f'<a href="../messages/{nid}.html">{label}</a>{_badges(n)}'

    def rec(nid, trail):
        if nid in trail:
            return (f'<li><a href="../messages/{nid}.html">{escape(ctx.node_label(nid))}</a>'
                    ' <span class="cycle">↩ 引用环(边保留,不再展开)</span></li>')
        kids = children_map.get(nid, [])
        sub = ""
        if kids:
            sub = "<ul>" + "".join(rec(k, trail | {nid}) for k in kids) + "</ul>"
        return f"<li>{link(nid)}{sub}</li>"

    entries = conv["roots"] or [conv["entry"]]
    tree_html = '<ul class="tree">' + "".join(rec(e, frozenset()) for e in entries) + "</ul>"

    flags = " ".join(f'<span class="badge warn">{escape(f)}</span>' for f in conv["flags"])
    out = [f"<h1>{escape(conv['subject'])}</h1><p>{flags}</p>",
           f"<p>{conv['message_count']} 封邮件 · 会话节点 "
           f'<span class="digest">{conv["conv_id"]}</span></p>',
           f"<section><h2>会话树</h2>{tree_html}</section>"]

    seen, dlist = set(), []
    for m in conv["members"]:
        for d in ctx.diags_for(m):
            key = json.dumps(d, ensure_ascii=False, sort_keys=True)
            if key not in seen:
                seen.add(key)
                dlist.append(d)
    if dlist:
        items = "".join(f"<li>{escape(d['type'])}: "
                        f"{escape(json.dumps(d, ensure_ascii=False, sort_keys=True))}</li>"
                        for d in dlist)
        out.append(f"<section><h2>会话诊断</h2><ul>{items}</ul></section>")
    return "".join(out)



def _page(title: str, body: str, prefix: str) -> str:
    return ("<!DOCTYPE html>\n<html lang=\"zh-CN\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
            f"<title>{escape(title)}</title><style>{CSS}</style></head><body>"
            f"<header><a href=\"{prefix}index.html\">mailarch</a> · "
            "静态只读邮件档案(无脚本 · 不加载远程资源)</header>"
            f"<main>{body}</main>"
            "<footer>generated by mailarch — read-only static archive. "
            "附件按原始字节导出，打开附件文件请自行判断风险。</footer>"
            "</body></html>\n")


def _short(h, n=12):
    return (h or "")[:n]


def _size(n):
    if n is None:
        return ""
    if n < 1024:
        return f"{n} B"
    if n < 1024 * 1024:
        return f"{n / 1024:.1f} KiB"
    return f"{n / 1024 / 1024:.1f} MiB"


def _badges(node):
    b = []
    if node.get("message_id_synthesized"):
        b.append('<span class="badge warn">missing Message-ID</span>')
    if node.get("id_conflicts"):
        b.append('<span class="badge err">ID conflict</span>')
    if node.get("in_cycle"):
        b.append('<span class="badge err">cycle</span>')
    if node.get("ambiguous_parents"):
        b.append('<span class="badge warn">ambiguous parent</span>')
    if len(node.get("source_files") or []) > 1:
        b.append(f'<span class="badge">×{len(node["source_files"])} duplicates</span>')
    return "".join(b)


class _Ctx:
    def __init__(self, nodes, ghosts, threads):
        self.nodes = nodes
        self.ghosts = ghosts
        self.threads = threads
        self.conv = {c["conv_id"]: c for c in threads["conversations"]}

    def any_node(self, nid):
        return self.nodes.get(nid) or self.ghosts.get(nid)

    def node_label(self, nid):
        n = self.any_node(nid)
        if not n:
            return nid
        if n.get("placeholder"):
            return f"⚠ 缺失邮件 {n['message_id']}(占位节点)"
        subj = n.get("subject") or "(no subject)"
        return f"{subj} — {n.get('from') or '?'} — {n.get('date_iso') or '未知日期'}"

    def diags_for(self, nid):
        out = []
        for d in self.threads["diagnostics"]:
            if d.get("node") == nid or nid in d.get("nodes", []) or nid in d.get("members", []):
                out.append(d)
        return out


